CREATE OR REPLACE FUNCTION public.admin_set_garba_vortex_storm(
  p_mode text DEFAULT NULL,
  p_global_writes_per_minute integer DEFAULT NULL,
  p_region_writes_per_minute integer DEFAULT NULL,
  p_storm_free_pins_per_day integer DEFAULT NULL,
  p_storm_bump_radius_m integer DEFAULT NULL,
  p_refresh boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = public, extensions, net, pg_temp
AS $$
DECLARE
  v_before jsonb;
  v_after jsonb;
BEGIN
  IF NOT (
    coalesce(auth.jwt() ->> 'role', '') = 'service_role'
    OR public.is_platform_admin(auth.uid())
  ) THEN
    RAISE EXCEPTION 'forbidden' USING ERRCODE = '42501';
  END IF;

  IF p_mode IS NOT NULL AND p_mode NOT IN ('off', 'auto', 'on') THEN
    RAISE EXCEPTION 'storm_mode must be off, auto, or on';
  END IF;
  IF p_global_writes_per_minute IS NOT NULL
     AND (p_global_writes_per_minute < 1 OR p_global_writes_per_minute > 100000) THEN
    RAISE EXCEPTION 'storm_global_writes_per_minute out of range';
  END IF;
  IF p_region_writes_per_minute IS NOT NULL
     AND (p_region_writes_per_minute < 1 OR p_region_writes_per_minute > 100000) THEN
    RAISE EXCEPTION 'storm_region_writes_per_minute out of range';
  END IF;
  IF p_storm_free_pins_per_day IS NOT NULL
     AND (p_storm_free_pins_per_day < 0 OR p_storm_free_pins_per_day > 50) THEN
    RAISE EXCEPTION 'storm_free_pins_per_day out of range';
  END IF;
  IF p_storm_bump_radius_m IS NOT NULL
     AND (p_storm_bump_radius_m < 1 OR p_storm_bump_radius_m > 50000) THEN
    RAISE EXCEPTION 'storm_bump_radius_m out of range';
  END IF;

  v_before := jsonb_build_object(
    'config', (SELECT to_jsonb(c) FROM public.garba_vortex_config c WHERE c.id = 1),
    'state', (SELECT to_jsonb(s) FROM public.garba_vortex_storm_state s WHERE s.id = 1)
  );

  UPDATE public.garba_vortex_config
     SET storm_mode = coalesce(p_mode, storm_mode),
         storm_global_writes_per_minute = coalesce(p_global_writes_per_minute, storm_global_writes_per_minute),
         storm_region_writes_per_minute = coalesce(p_region_writes_per_minute, storm_region_writes_per_minute),
         storm_free_pins_per_day = coalesce(p_storm_free_pins_per_day, storm_free_pins_per_day),
         storm_bump_radius_m = coalesce(p_storm_bump_radius_m, storm_bump_radius_m),
         updated_at = now()
   WHERE id = 1;

  PERFORM public.garba_vortex_evaluate_storm();
  IF coalesce(p_refresh, false) THEN
    PERFORM public.refresh_garba_vortex_heatmap_snapshot(true);
  END IF;

  v_after := jsonb_build_object(
    'config', (SELECT to_jsonb(c) FROM public.garba_vortex_config c WHERE c.id = 1),
    'state', (SELECT to_jsonb(s) FROM public.garba_vortex_storm_state s WHERE s.id = 1),
    'refresh', coalesce(p_refresh, false)
  );

  IF EXISTS (
    SELECT 1
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'private'
      AND p.proname = 'write_admin_audit'
  ) THEN
    PERFORM private.write_admin_audit(
      'garba_vortex_storm',
      'garba_vortex_config',
      '1',
      v_before,
      v_after
    );
  END IF;

  RETURN public.admin_get_garba_vortex_storm();
END;
$$;

