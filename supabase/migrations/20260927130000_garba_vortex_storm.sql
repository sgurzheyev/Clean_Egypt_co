--   supabase db query --linked -f supabase/migrations/20260927130000_garba_vortex_storm.sql
-- Idempotent. Re-running does NOT reset tuned garba_vortex_config values
-- and does NOT clear an in-progress storm flag.
--
-- When free-pin creates/bumps cross storm_global_writes_per_minute or
-- storm_region_writes_per_minute, the map stops serving isolated spikes.
-- get_garba_vortex_heatmap reads a coarse averaged snapshot (refreshed at
-- most every storm_snapshot_ttl_seconds). place_free_vortex_pin tightens
-- the daily cap and widens the bump radius. HTTP caching lives on
-- /api/garba-vortex-heatmap (Cache-Control), not in Postgres.
--
-- search_path matches live functions: public, extensions, net, pg_temp.
-- ============================================================================

