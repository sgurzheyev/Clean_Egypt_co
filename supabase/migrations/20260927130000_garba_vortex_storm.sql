-- Tunables. Defaults fill the existing singleton; later edits stick.
-- ---------------------------------------------------------------------------
ALTER TABLE public.garba_vortex_config
  ADD COLUMN IF NOT EXISTS storm_mode text NOT NULL DEFAULT 'auto',
  ADD COLUMN IF NOT EXISTS storm_global_writes_per_minute integer NOT NULL DEFAULT 60,
  ADD COLUMN IF NOT EXISTS storm_region_writes_per_minute integer NOT NULL DEFAULT 12,
  ADD COLUMN IF NOT EXISTS storm_region_km integer NOT NULL DEFAULT 25,
  ADD COLUMN IF NOT EXISTS storm_snapshot_ttl_seconds integer NOT NULL DEFAULT 60,
  ADD COLUMN IF NOT EXISTS storm_free_pins_per_day integer NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS storm_bump_radius_m integer NOT NULL DEFAULT 500,
  ADD COLUMN IF NOT EXISTS storm_same_spot_radius_m integer NOT NULL DEFAULT 200,
  ADD COLUMN IF NOT EXISTS storm_cache_seconds integer NOT NULL DEFAULT 30,
  ADD COLUMN IF NOT EXISTS storm_cooldown_seconds integer NOT NULL DEFAULT 120,
  ADD COLUMN IF NOT EXISTS storm_release_ratio numeric NOT NULL DEFAULT 0.60,
  ADD COLUMN IF NOT EXISTS storm_cell_m integer NOT NULL DEFAULT 8000;

DO $storm_chk$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'garba_vortex_config_storm_ranges'
      AND conrelid = 'public.garba_vortex_config'::regclass
  ) THEN
    ALTER TABLE public.garba_vortex_config
      ADD CONSTRAINT garba_vortex_config_storm_ranges
      CHECK (
        storm_mode IN ('off', 'auto', 'on')
        AND storm_global_writes_per_minute BETWEEN 1 AND 100000
        AND storm_region_writes_per_minute BETWEEN 1 AND 100000
        AND storm_region_km BETWEEN 1 AND 500
        AND storm_snapshot_ttl_seconds BETWEEN 5 AND 3600
        AND storm_free_pins_per_day BETWEEN 0 AND 50
        AND storm_bump_radius_m BETWEEN 1 AND 50000
        AND storm_same_spot_radius_m BETWEEN 1 AND 50000
        AND storm_cache_seconds BETWEEN 5 AND 300
        AND storm_cooldown_seconds BETWEEN 0 AND 3600
        AND storm_release_ratio BETWEEN 0.05 AND 0.95
        AND storm_cell_m BETWEEN 500 AND 200000
      ) NOT VALID;
  END IF;
END
$storm_chk$;

