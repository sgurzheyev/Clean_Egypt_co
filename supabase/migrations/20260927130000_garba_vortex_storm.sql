CREATE OR REPLACE FUNCTION public.garba_vortex_evaluate_storm()
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions, net, pg_temp
AS $$
DECLARE
  v_cfg public.garba_vortex_config;
  v_state public.garba_vortex_storm_state;
  v_mode text;
  v_global integer := 0;
  v_peak integer := 0;
  v_peak_key text;
  v_active boolean;
  v_reason text;
  v_since timestamptz;
  v_ratio numeric;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('garba-storm'));

  SELECT * INTO v_cfg FROM public.garba_vortex_config WHERE id = 1;
  IF NOT FOUND THEN
    RETURN false;
  END IF;

  INSERT INTO public.garba_vortex_storm_state (id)
  VALUES (1)
  ON CONFLICT (id) DO NOTHING;

  SELECT * INTO v_state
  FROM public.garba_vortex_storm_state
  WHERE id = 1
  FOR UPDATE;

  SELECT count(*)::integer
    INTO v_global
  FROM public.garba_vortex_write_events
  WHERE created_at >= now() - interval '1 minute';

  SELECT e.region_key, count(*)::integer
    INTO v_peak_key, v_peak
  FROM public.garba_vortex_write_events e
  WHERE e.created_at >= now() - interval '1 minute'
  GROUP BY e.region_key
  ORDER BY count(*) DESC, e.region_key
  LIMIT 1;

  v_global := coalesce(v_global, 0);
  v_peak := coalesce(v_peak, 0);
  v_mode := coalesce(v_cfg.storm_mode, 'auto');
  v_ratio := least(0.95::numeric, greatest(0.05::numeric, coalesce(v_cfg.storm_release_ratio, 0.60)));

  IF v_mode = 'on' THEN
    v_active := true;
    v_reason := 'forced_on';
  ELSIF v_mode = 'off' THEN
    v_active := false;
    v_reason := 'forced_off';
  ELSIF NOT coalesce(v_state.active, false) THEN
    IF v_global >= v_cfg.storm_global_writes_per_minute THEN
      v_active := true;
      v_reason := 'global';
    ELSIF v_peak >= v_cfg.storm_region_writes_per_minute THEN
      v_active := true;
      v_reason := 'region';
    ELSE
      v_active := false;
      v_reason := 'clear';
    END IF;
  ELSE
    v_active := true;
    IF v_global >= v_cfg.storm_global_writes_per_minute THEN
      v_reason := 'global';
    ELSIF v_peak >= v_cfg.storm_region_writes_per_minute THEN
      v_reason := 'region';
    ELSIF v_global < (v_cfg.storm_global_writes_per_minute * v_ratio)
      AND v_peak < (v_cfg.storm_region_writes_per_minute * v_ratio)
      AND coalesce(v_state.active_since, now())
        <= now() - make_interval(secs => greatest(coalesce(v_cfg.storm_cooldown_seconds, 0), 0))
    THEN
      v_active := false;
      v_reason := 'clear';
    ELSE
      v_reason := 'cooldown';
    END IF;
  END IF;

  IF v_active THEN
    v_since := CASE
      WHEN coalesce(v_state.active, false) THEN coalesce(v_state.active_since, now())
      ELSE now()
    END;
  ELSE
    v_since := NULL;
  END IF;

  UPDATE public.garba_vortex_storm_state
     SET active = v_active,
         reason = v_reason,
         global_writes = v_global,
         peak_region_writes = v_peak,
         peak_region_key = v_peak_key,
         evaluated_at = now(),
         active_since = v_since
   WHERE id = 1;

  RETURN v_active;
END;
$$;

REVOKE ALL ON FUNCTION public.garba_vortex_evaluate_storm() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.garba_vortex_evaluate_storm() FROM anon;
REVOKE ALL ON FUNCTION public.garba_vortex_evaluate_storm() FROM authenticated;

COMMENT ON FUNCTION public.garba_vortex_evaluate_storm() IS
  'Owner-only. auto mode trips on global or per-region writes/minute and holds through storm_cooldown_seconds until both rates fall under storm_release_ratio.';

CREATE OR REPLACE FUNCTION public.garba_vortex_record_write(
  p_creator uuid,
  p_lat double precision,
  p_lng double precision,
  p_kind text
