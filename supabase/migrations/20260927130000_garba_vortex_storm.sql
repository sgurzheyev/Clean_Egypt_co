-- ---------------------------------------------------------------------------
-- Admin indicator. Counts stay here; the public status RPC does not return them.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.admin_get_garba_vortex_storm()
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = public, extensions, net, pg_temp
AS $$
DECLARE
  v_cfg public.garba_vortex_config;
  v_state public.garba_vortex_storm_state;
  v_cells integer := 0;
  v_snap timestamptz;
BEGIN
  IF NOT (
    coalesce(auth.jwt() ->> 'role', '') = 'service_role'
    OR public.is_platform_admin(auth.uid())
  ) THEN
    RAISE EXCEPTION 'forbidden' USING ERRCODE = '42501';
  END IF;

  PERFORM public.garba_vortex_evaluate_storm();

  SELECT * INTO v_cfg FROM public.garba_vortex_config WHERE id = 1;
  SELECT * INTO v_state FROM public.garba_vortex_storm_state WHERE id = 1;
  SELECT count(*)::integer, max(refreshed_at)
    INTO v_cells, v_snap
  FROM public.garba_vortex_heatmap_snapshot;

  RETURN jsonb_build_object(
    'storm', coalesce(v_state.active, false),
    'reason', coalesce(v_state.reason, 'clear'),
    'mode', coalesce(v_cfg.storm_mode, 'auto'),
    'global_writes', coalesce(v_state.global_writes, 0),
    'global_threshold', v_cfg.storm_global_writes_per_minute,
    'peak_region_writes', coalesce(v_state.peak_region_writes, 0),
    'peak_region_key', v_state.peak_region_key,
    'region_threshold', v_cfg.storm_region_writes_per_minute,
    'region_km', v_cfg.storm_region_km,
    'evaluated_at', v_state.evaluated_at,
    'active_since', v_state.active_since,
    'snapshot_refreshed_at', coalesce(v_snap, v_state.snapshot_refreshed_at),
    'snapshot_cells', coalesce(v_cells, 0),
    'cache_seconds', v_cfg.storm_cache_seconds,
    'snapshot_ttl_seconds', v_cfg.storm_snapshot_ttl_seconds,
    'cooldown_seconds', v_cfg.storm_cooldown_seconds,
    'release_ratio', v_cfg.storm_release_ratio,
    'storm_free_pins_per_day', v_cfg.storm_free_pins_per_day,
    'storm_bump_radius_m', v_cfg.storm_bump_radius_m,
    'storm_same_spot_radius_m', v_cfg.storm_same_spot_radius_m,
    'storm_cell_m', v_cfg.storm_cell_m,
    'free_pins_per_day', v_cfg.free_pins_per_day,
    'bump_radius_m', v_cfg.bump_radius_m
  );
END;
$$;

