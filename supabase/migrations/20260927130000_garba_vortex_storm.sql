CREATE OR REPLACE FUNCTION public.refresh_garba_vortex_heatmap_snapshot(p_force boolean DEFAULT false)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions, net, pg_temp
AS $$
DECLARE
  v_ttl integer;
  v_cell_m integer;
  v_fresh timestamptz;
BEGIN
  SELECT storm_snapshot_ttl_seconds, storm_cell_m
    INTO v_ttl, v_cell_m
  FROM public.garba_vortex_config
  WHERE id = 1;

  v_ttl := greatest(coalesce(v_ttl, 60), 5);
  v_cell_m := greatest(coalesce(v_cell_m, 8000), 500);

  SELECT max(refreshed_at) INTO v_fresh FROM public.garba_vortex_heatmap_snapshot;
  IF NOT coalesce(p_force, false)
     AND v_fresh IS NOT NULL
     AND v_fresh >= now() - make_interval(secs => v_ttl) THEN
    RETURN false;
  END IF;

  -- Stampede guard. A waiter keeps serving the previous snapshot.
  IF NOT pg_try_advisory_xact_lock(hashtext('garba-storm-snapshot')) THEN
    RETURN false;
  END IF;

  SELECT max(refreshed_at) INTO v_fresh FROM public.garba_vortex_heatmap_snapshot;
  IF NOT coalesce(p_force, false)
     AND v_fresh IS NOT NULL
     AND v_fresh >= now() - make_interval(secs => v_ttl) THEN
    RETURN false;
  END IF;

  DELETE FROM public.garba_vortex_heatmap_snapshot;

  INSERT INTO public.garba_vortex_heatmap_snapshot (
    grid_ix, grid_iy, lng, lat, weight, point_count, report_count, max_severity, refreshed_at
  )
  WITH raw AS (
    SELECT
      round(
        m.location_lng / (
          v_cell_m::double precision / (111320.0 * greatest(cos(radians(m.location_lat)), 0.2))
        )
      )::integer AS ix,
      round(m.location_lat / (v_cell_m::double precision / 111320.0))::integer AS iy,
      avg(m.location_lng) AS lng,
      avg(m.location_lat) AS lat,
      count(*)::integer AS point_count,
      count(*) FILTER (
        WHERE coalesce(m.is_report, false)
          OR lower(coalesce(m.status::text, '')) = 'reported'
      )::integer AS report_count,
      max(m.severity_score)::integer AS max_severity,
      least(
        12::numeric,
        2.5
          + ln(count(*)::numeric + 1) * 1.7
          + ln(coalesce(sum(m.severity_score), 0)::numeric + 1) * 0.35
      ) AS weight
    FROM public.missions m
    WHERE m.hidden_at IS NULL
      AND m.location_lat IS NOT NULL
      AND m.location_lng IS NOT NULL
      AND public.garba_vortex_pin_visible(
        m.status::text,
        m.hidden_at,
        m.created_at,
        m.current_funding,
        m.history_public_until,
        m.media_purged_at
      )
    GROUP BY 1, 2
  ),
  glob AS (
    SELECT avg(weight) AS avg_weight FROM raw
  ),
  neigh AS (
    SELECT r.ix, r.iy, avg(n.weight) AS avg_weight
    FROM raw r
    JOIN raw n
      ON abs(n.ix - r.ix) <= 1
     AND abs(n.iy - r.iy) <= 1
     AND NOT (n.ix = r.ix AND n.iy = r.iy)
    GROUP BY r.ix, r.iy
  )
  SELECT
    r.ix,
    r.iy,
    r.lng,
    r.lat,
    least(
      12::numeric,
      greatest(
        0.15::numeric,
        CASE
          WHEN r.point_count = 1 AND neigh.avg_weight IS NULL THEN
            0.35 * (0.7 * r.weight + 0.3 * coalesce(glob.avg_weight, r.weight))
          ELSE
            0.7 * r.weight + 0.3 * coalesce(neigh.avg_weight, r.weight)
        END
      )
    ) AS weight,
    r.point_count,
    r.report_count,
    greatest(1, least(100, coalesce(r.max_severity, 1))),
    now()
  FROM raw r
  CROSS JOIN glob
  LEFT JOIN neigh ON neigh.ix = r.ix AND neigh.iy = r.iy
  ORDER BY 5 DESC
  LIMIT 4000;

  UPDATE public.garba_vortex_storm_state
     SET snapshot_refreshed_at = now()
   WHERE id = 1;

  RETURN true;
END;
$$;

REVOKE ALL ON FUNCTION public.refresh_garba_vortex_heatmap_snapshot(boolean) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.refresh_garba_vortex_heatmap_snapshot(boolean) FROM anon;
REVOKE ALL ON FUNCTION public.refresh_garba_vortex_heatmap_snapshot(boolean) FROM authenticated;

COMMENT ON FUNCTION public.refresh_garba_vortex_heatmap_snapshot(boolean) IS
  'Owner-only. Rebuilds the averaged storm heatmap. Skips work inside the TTL unless p_force. Isolated-spike weights are not used.';

-- ---------------------------------------------------------------------------
-- Heatmap. DEFINER so anon can trip evaluate/refresh without EXECUTE on them.
-- hidden_at rows stay excluded (same visible set as the invoker version).
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.get_garba_vortex_heatmap(
  p_min_lng double precision,
  p_min_lat double precision,
  p_max_lng double precision,
  p_max_lat double precision,
  p_zoom double precision DEFAULT 4,
  p_include_reports boolean DEFAULT true
)
RETURNS TABLE (
  lng double precision,
  lat double precision,
  weight numeric,
  point_count integer,
  max_severity integer,
  isolated boolean,
  black_hole boolean
)
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = public, extensions, net, pg_temp
AS $$
DECLARE
  v_active boolean := false;
  v_eval timestamptz;
  v_have boolean := false;
  v_meters double precision;
  v_mid_lat double precision;
  v_cos double precision;
  v_dlat double precision;
  v_dlng double precision;
  v_bh integer;
  v_spikes boolean;
BEGIN
  IF p_min_lng IS NULL OR p_min_lat IS NULL OR p_max_lng IS NULL OR p_max_lat IS NULL THEN
    RETURN;
  END IF;

  SELECT s.active, s.evaluated_at
    INTO v_active, v_eval
  FROM public.garba_vortex_storm_state s
  WHERE s.id = 1;

  IF v_eval IS NULL OR v_eval < now() - interval '5 seconds' THEN
    v_active := public.garba_vortex_evaluate_storm();
  END IF;
  v_active := coalesce(v_active, false);

  IF v_active THEN
    PERFORM public.refresh_garba_vortex_heatmap_snapshot(false);
    SELECT EXISTS (SELECT 1 FROM public.garba_vortex_heatmap_snapshot) INTO v_have;
    IF v_have THEN
      RETURN QUERY
      SELECT
        s.lng,
        s.lat,
        CASE
          WHEN coalesce(p_include_reports, true) OR s.report_count <= 0 THEN s.weight
          ELSE s.weight * (s.point_count - s.report_count)::numeric / greatest(s.point_count, 1)
        END AS weight,
        CASE
          WHEN coalesce(p_include_reports, true) THEN s.point_count
          ELSE (s.point_count - s.report_count)
        END AS point_count,
        s.max_severity,
        false AS isolated,
        false AS black_hole
      FROM public.garba_vortex_heatmap_snapshot s
      WHERE s.lat BETWEEN least(p_min_lat, p_max_lat) AND greatest(p_min_lat, p_max_lat)
        AND (
          (
            p_min_lng <= p_max_lng
            AND s.lng BETWEEN p_min_lng AND p_max_lng
          )
          OR (
            p_min_lng > p_max_lng
            AND (s.lng >= p_min_lng OR s.lng <= p_max_lng)
          )
        )
        AND (
          coalesce(p_include_reports, true)
          OR s.point_count > s.report_count
        )
      ORDER BY 3 DESC
      LIMIT 2000;
      RETURN;
    END IF;
  END IF;

  IF v_active THEN
    SELECT greatest(coalesce(storm_cell_m, 8000), 500)::double precision
      INTO v_meters
    FROM public.garba_vortex_config
    WHERE id = 1;
    v_meters := coalesce(v_meters, 8000);
  ELSE
    v_meters := public.garba_vortex_cell_m(p_zoom);
  END IF;

  v_spikes := NOT v_active;
  v_mid_lat := (least(p_min_lat, p_max_lat) + greatest(p_min_lat, p_max_lat)) / 2.0;
  v_cos := greatest(cos(radians(v_mid_lat)), 0.2);
  v_dlat := v_meters / 111320.0;
  v_dlng := v_meters / (111320.0 * v_cos);

  SELECT black_hole_min_severity INTO v_bh
  FROM public.garba_vortex_config
  WHERE id = 1;
  v_bh := coalesce(v_bh, 8);

  RETURN QUERY
  SELECT
    avg(m.location_lng)::double precision AS lng,
    avg(m.location_lat)::double precision AS lat,
    (
      CASE
        WHEN v_spikes AND count(*) = 1 AND bool_or(m.is_isolated) THEN
          least(12::numeric, 8::numeric + max(m.severity_score)::numeric / 20.0)
        ELSE
          least(
            12::numeric,
            2.5
              + ln(count(*)::numeric + 1) * 1.7
              + ln(sum(m.severity_score)::numeric + 1) * 0.35
          )
      END
    ) AS weight,
    count(*)::integer AS point_count,
    max(m.severity_score)::integer AS max_severity,
    CASE WHEN v_spikes THEN bool_or(m.is_isolated) ELSE false END AS isolated,
    (
      v_spikes
      AND count(*) = 1
      AND bool_or(m.is_isolated)
      AND max(m.severity_score) >= v_bh
    ) AS black_hole
  FROM public.missions m
  WHERE m.hidden_at IS NULL
    AND m.location_lat IS NOT NULL
    AND m.location_lng IS NOT NULL
    AND m.location_lat BETWEEN least(p_min_lat, p_max_lat) AND greatest(p_min_lat, p_max_lat)
    AND (
      (
        p_min_lng <= p_max_lng
        AND m.location_lng BETWEEN p_min_lng AND p_max_lng
      )
      OR (
        p_min_lng > p_max_lng
        AND (m.location_lng >= p_min_lng OR m.location_lng <= p_max_lng)
      )
    )
    AND public.garba_vortex_pin_visible(
      m.status::text,
      m.hidden_at,
      m.created_at,
      m.current_funding,
      m.history_public_until,
      m.media_purged_at
    )
    AND (
      coalesce(p_include_reports, true)
      OR NOT (
        coalesce(m.is_report, false)
        OR lower(coalesce(m.status::text, '')) = 'reported'
      )
    )
  GROUP BY
    round(m.location_lat / v_dlat),
    round(m.location_lng / v_dlng)
  ORDER BY 3 DESC
  LIMIT 2000;
END;
$$;

