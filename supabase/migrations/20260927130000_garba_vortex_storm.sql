CREATE OR REPLACE FUNCTION public.garba_vortex_region_key(
  p_lat double precision,
  p_lng double precision,
  p_km integer
)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = public, extensions, net, pg_temp
AS $$
  SELECT
    round(p_lat / (greatest(coalesce(p_km, 25), 1)::double precision / 111.32))::text
    || ':'
    || round(
      p_lng / (
        greatest(coalesce(p_km, 25), 1)::double precision
        / (111.32 * greatest(cos(radians(p_lat)), 0.2))
      )
    )::text;
$$;

