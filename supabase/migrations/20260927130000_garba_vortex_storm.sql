RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions, net, pg_temp
AS $$
DECLARE
  v_km integer;
  v_kind text := CASE WHEN p_kind = 'bump' THEN 'bump' ELSE 'create' END;
BEGIN
  SELECT storm_region_km INTO v_km FROM public.garba_vortex_config WHERE id = 1;
  v_km := greatest(coalesce(v_km, 25), 1);

  INSERT INTO public.garba_vortex_write_events (creator_id, lat, lng, region_key, kind)
